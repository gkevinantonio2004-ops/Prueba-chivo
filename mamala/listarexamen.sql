

CREATE DATABASE EXAMEN
GO
USE EXAMEN
GO

CREATE TABLE CLIENTE
(
	ID_CLIENTE INT PRIMARY KEY IDENTITY(1,1),
	NOMBRE_CLIENTE VARCHAR(50),
	DIRECCION VARCHAR(50),
	FECHA_INGRESO DATETIME
)
GO

CREATE OR ALTER PROC LISTARCLIENTE 
AS
BEGIN TRY
	BEGIN TRAN
	SELECT 
	C.ID_CLIENTE AS ID,
	C.NOMBRE_CLIENTE,
	C.DIRECCION,
	C.FECHA_INGRESO
	FROM CLIENTE C
	COMMIT
END TRY
BEGIN CATCH
ROLLBACK
PRINT'EL CLIENTE NO PUDO LISTAR POR EL ERROR: '+ ERROR_MESSAGE()
END CATCH
GO 

CREATE OR ALTER PROC INSERTAR_CLIENTE
(
	@NOMBRE_CLIENTE VARCHAR(50),
	@DIRECCION VARCHAR(50)
)
AS 
BEGIN TRY
	BEGIN TRAN
	SET NOCOUNT ON
		DECLARE @FECHA_INGRESO DATETIME
	INSERT INTO CLIENTE (NOMBRE_CLIENTE, DIRECCION,FECHA_INGRESO)
	 VALUES (@NOMBRE_CLIENTE, @DIRECCION,GETDATE())
	COMMIT
	PRINT'EL CLIENTE SE INSERTO CORRECTAMENTE'
END TRY
BEGIN CATCH
ROLLBACK
PRINT'NO SE PUDO INSERTAR EL CLIENTE POR EL ERROR: ' + ERROR_MESSAGE()
END CATCH
GO

